"""Convert NIST's ACVP ML-DSA / SLH-DSA vectors into tests/kat/*_acvp.txt.

    acvp_sig_to_kat.py mldsa  KEYGEN SIGGEN SIGVER SOURCE > mldsa_acvp.txt
    acvp_sig_to_kat.py slhdsa KEYGEN SIGGEN SIGVER SOURCE [--sigver-sets A,B]
        > slhdsa_acvp.txt

Inputs are internalProjection.json from usnistgov/ACVP-Server
gen-val/json-files/{ML-DSA,SLH-DSA}-{keyGen,sigGen,sigVer}-FIPS20{4,5}.
SOURCE is a provenance line copied into the header.

Only the "external" signature interface with "pure" pre-hash mode is
converted: that is the API libpqc-dyber exposes (pqc_sig_sign_ctx /
pqc_sig_verify_ctx). The internal interface, HashML-DSA / HashSLH-DSA
(pre-hash) and ML-DSA's external-mu groups are counted in the header but
not converted, since there is nothing to call them through.

SLH-DSA sigVer vectors carry whole signatures (8 to 50 KB each, about
10 MB as hex). --sigver-sets keeps only the named parameter sets; without
it every set is kept.

One test per line, fields separated by spaces, hex, "-" for empty:

  keygen ALG TCID RNG sha256(pk) sha256(sk)
  siggen ALG TCID sk msg ctx RNG sha256(sig)
  sigver ALG TCID pk msg ctx sig PASS

RNG is exactly what the library's RNG hook must hand out for that call:
ML-DSA key generation: xi (32 bytes); SLH-DSA key generation:
SK.seed || SK.prf || PK.seed; ML-DSA signing: rnd (zeros when
deterministic); SLH-DSA signing: opt_rand (PK.seed when deterministic).
"""
import collections
import hashlib
import json
import sys


def h(x):
    return hashlib.sha256(bytes.fromhex(x)).hexdigest()


def f(x):
    return x if x else "-"


def main():
    scheme = sys.argv[1]
    kg, sg, sv = (json.load(open(p)) for p in sys.argv[2:5])
    source = sys.argv[5]
    keep_sets = None
    if len(sys.argv) > 7 and sys.argv[6] == "--sigver-sets":
        keep_sets = set(sys.argv[7].split(","))

    skipped = collections.Counter()
    lines = []

    for g in kg["testGroups"]:
        alg = g["parameterSet"]
        for t in g["tests"]:
            if scheme == "mldsa":
                rng = t["seed"]
            else:
                rng = t["skSeed"] + t["skPrf"] + t["pkSeed"]
            lines.append(f"keygen {alg} {t['tcId']} {rng} {h(t['pk'])} {h(t['sk'])}")

    def supported(g, what):
        iface, pre = g.get("signatureInterface"), g.get("preHash")
        if g.get("externalMu"):
            skipped[what + " external-mu"] += len(g["tests"])
            return False
        if iface != "external":
            skipped[what + " internal interface"] += len(g["tests"])
            return False
        if pre != "pure":
            skipped[what + " pre-hash"] += len(g["tests"])
            return False
        return True

    for g in sg["testGroups"]:
        if not supported(g, "sigGen"):
            continue
        alg, det = g["parameterSet"], g["deterministic"]
        for t in g["tests"]:
            if scheme == "mldsa":
                rng = "00" * 32 if det else t["rnd"]
            else:
                n = len(t["sk"]) // 8          # sk = 4n bytes
                rng = t["sk"][4 * n:6 * n] if det else t["additionalRandomness"]
            lines.append(f"siggen {alg} {t['tcId']} {t['sk']} {f(t['message'])} "
                         f"{f(t.get('context', ''))} {rng} {h(t['signature'])}")

    for g in sv["testGroups"]:
        if not supported(g, "sigVer"):
            continue
        alg = g["parameterSet"]
        if keep_sets is not None and alg not in keep_sets:
            skipped["sigVer outside the kept parameter sets"] += len(g["tests"])
            continue
        for t in g["tests"]:
            lines.append(f"sigver {alg} {t['tcId']} {t['pk']} {f(t['message'])} "
                         f"{f(t.get('context', ''))} {t['signature']} "
                         f"{int(bool(t['testPassed']))}")

    name = "ML-DSA (FIPS 204)" if scheme == "mldsa" else "SLH-DSA (FIPS 205)"
    print(f"# {name} known-answer vectors from NIST ACVP")
    print("# " + source)
    print("# Generated by tests/kat/tools/acvp_sig_to_kat.py; see that file")
    print("# for the line format.")
    for k, v in sorted(skipped.items()):
        print(f"# not converted: {v} {k} vectors")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
