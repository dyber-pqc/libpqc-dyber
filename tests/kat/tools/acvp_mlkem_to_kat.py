"""Convert NIST's ACVP ML-KEM vectors into tests/kat/mlkem_acvp.txt.

    acvp_mlkem_to_kat.py KEYGEN_JSON ENCAPDECAP_JSON SOURCE > mlkem_acvp.txt

The inputs are internalProjection.json from
usnistgov/ACVP-Server/gen-val/json-files/ML-KEM-keyGen-FIPS203 and
ML-KEM-encapDecap-FIPS203. SOURCE is a free-text provenance line (repo,
commit, file hashes) copied into the header.

One test per line, fields separated by spaces, all hex:

  keygen  SET TCID d z sha256(ek) sha256(dk)
  encap   SET TCID ek m sha256(c) k
  decap   SET TCID dk c k
  ekcheck SET TCID ek PASS            (PASS is 1 if the key is valid)
  dkcheck SET TCID dk PASS

Inputs are kept verbatim; large outputs are kept as SHA-256 so the file
stays small. SET is 512, 768 or 1024.
"""
import hashlib
import json
import sys


def h(x):
    return hashlib.sha256(bytes.fromhex(x)).hexdigest()


def main():
    kg = json.load(open(sys.argv[1]))
    ed = json.load(open(sys.argv[2]))
    print("# ML-KEM (FIPS 203) known-answer vectors from NIST ACVP")
    print("# " + sys.argv[3])
    print("# Generated by tests/kat/tools/acvp_mlkem_to_kat.py; see that file")
    print("# for the line format.")
    for g in kg["testGroups"]:
        ps = g["parameterSet"].split("-")[-1]
        for t in g["tests"]:
            print("keygen", ps, t["tcId"], t["d"], t["z"], h(t["ek"]), h(t["dk"]))
    for g in ed["testGroups"]:
        ps = g["parameterSet"].split("-")[-1]
        fn = g["function"]
        for t in g["tests"]:
            if fn == "encapsulation":
                print("encap", ps, t["tcId"], t["ek"], t["m"], h(t["c"]), t["k"])
            elif fn == "decapsulation":
                print("decap", ps, t["tcId"], t["dk"], t["c"], t["k"])
            elif fn == "encapsulationKeyCheck":
                print("ekcheck", ps, t["tcId"], t["ek"], int(bool(t["testPassed"])))
            elif fn == "decapsulationKeyCheck":
                print("dkcheck", ps, t["tcId"], t["dk"], int(bool(t["testPassed"])))
            else:
                raise SystemExit("unknown function " + fn)


if __name__ == "__main__":
    main()
